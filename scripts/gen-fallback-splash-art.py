#!/usr/bin/env python3
"""Draws the enhanced weather's splash art for the fallback layer.

The art is this project's own: a soft ring and a soft dot computed here, not
traced from or derived from any game file. White shapes in the `OAGMASK` text
format (`crates/texture/src/mask.rs`), 64 x 32: the left 32 x 32 cell is the
ring a splash spreads, the right cell the dot a droplet and a settled flake are.
The effects' own tint and fade supply colour and alpha. Cell layout is mirrored
by `oag_raceplay::scenery_fx::splash::RING` and `DOT`.

Run from the repository root:

    python3 scripts/gen-fallback-splash-art.py

It rewrites `assets/fallback/Data/Psys/Tex/OAGSplash.oagmask`, which is checked in.
"""

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "assets/fallback/Data/Psys/Tex/OAGSplash.oagmask"
CELL = 32
SS = 4


def smooth(edge0, edge1, x):
    t = min(max((x - edge0) / (edge1 - edge0), 0.0), 1.0)
    return t * t * (3 - 2 * t)


def ring(x, y):
    r = math.hypot(x, y)
    return smooth(0.50, 0.68, r) * (1 - smooth(0.78, 0.95, r))


def dot(x, y):
    r = math.hypot(x, y)
    return 1 - smooth(0.25, 0.95, r)


def sample(shape, px, py):
    total = 0.0
    for sy in range(SS):
        for sx in range(SS):
            x = ((px + (sx + 0.5) / SS) / CELL) * 2 - 1
            y = ((py + (sy + 0.5) / SS) / CELL) * 2 - 1
            total += shape(x, y)
    return total / (SS * SS)


def digit(alpha):
    n = round(alpha * 15)
    return "." if n == 0 else "0123456789abcdef"[n]


rows = []
for py in range(CELL):
    row = ""
    for shape in (ring, dot):
        for px in range(CELL):
            row += digit(sample(shape, px, py))
    rows.append(row)
OUT.write_text(
    "# This project's own splash art for the enhanced weather; generated by\n"
    "# scripts/gen-fallback-splash-art.py. Left cell a ring, right cell a dot.\n"
    f"OAGMASK {2 * CELL} {CELL}\n" + "\n".join(rows) + "\n"
)
