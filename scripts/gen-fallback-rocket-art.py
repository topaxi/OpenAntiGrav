#!/usr/bin/env python3
"""Draws the puff sprites of this project's own rocket effect for the fallback layer.

The art is this project's own: a lumpy puff computed here from value noise, not
traced from or derived from any game file. White shapes in the `OAGMASK` text
format (`crates/texture/src/mask.rs`), 64 x 64 each: a disc whose edge wanders,
dense inside and clear at the border, so a row of them reads as rolling smoke
and one alone as a chunky fireball. The effect files that name them
(`assets/fallback/Data/Psys/OAGRocket*.toml`) supply colour and fade.

Run from the repository root:

    python3 scripts/gen-fallback-rocket-art.py

It rewrites `assets/fallback/Data/Psys/Tex/OAGRocketPuff<n>.oagmask`, which are
checked in.
"""

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "assets/fallback/Data/Psys/Tex"
SIZE = 64
SS = 3
PUFFS = 4
MASK = 0xFFFFFFFF


def lattice(x, y, seed):
    h = (x * 0x9E3779B1 + y * 0x85EBCA77 + seed * 0xC2B2AE3D) & MASK
    h ^= h >> 15
    h = (h * 0x2C1B3C6D) & MASK
    h ^= h >> 12
    h = (h * 0x297A2D39) & MASK
    h ^= h >> 15
    return (h >> 8) / 16777216.0


def noise(x, y, seed):
    x0, y0 = math.floor(x), math.floor(y)
    fx, fy = x - x0, y - y0
    sx, sy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    top = lattice(x0, y0, seed) + (lattice(x0 + 1, y0, seed) - lattice(x0, y0, seed)) * sx
    bottom = lattice(x0, y0 + 1, seed) + (lattice(x0 + 1, y0 + 1, seed) - lattice(x0, y0 + 1, seed)) * sx
    return top + (bottom - top) * sy


def billow(x, y, seed):
    return (noise(x, y, seed) * 4 + noise(x * 2, y * 2, seed ^ 0x51) * 2 + noise(x * 4, y * 4, seed ^ 0xA3)) / 7


def smooth(edge0, edge1, x):
    t = min(max((x - edge0) / (edge1 - edge0), 0.0), 1.0)
    return t * t * (3 - 2 * t)


def puff(x, y, seed):
    r = math.hypot(x, y)
    edge = 0.56 + 0.34 * billow(x * 2.2 + 7, y * 2.2 + 3, seed)
    body = smooth(edge, edge - 0.3, r)
    grain = 0.7 + 0.3 * billow(x * 3.5 + 19, y * 3.5 + 11, seed ^ 0x77)
    # Clear at the border whatever the noise says, so no quad edge shows.
    return body * grain * (1 - smooth(0.86, 0.97, max(abs(x), abs(y))))


def digit(alpha):
    n = round(alpha * 15)
    return "." if n == 0 else "0123456789abcdef"[n]


for seed in range(1, PUFFS + 1):
    rows = []
    for py in range(SIZE):
        row = ""
        for px in range(SIZE):
            total = 0.0
            for sy in range(SS):
                for sx in range(SS):
                    x = ((px + (sx + 0.5) / SS) / SIZE) * 2 - 1
                    y = ((py + (sy + 0.5) / SS) / SIZE) * 2 - 1
                    total += puff(x, y, seed)
            row += digit(total / (SS * SS))
        rows.append(row)
    (OUT / f"OAGRocketPuff{seed}.oagmask").write_text(
        "# This project's own puff sprite for its rocket effect (graphics.own_rockets);\n"
        "# generated by scripts/gen-fallback-rocket-art.py.\n"
        f"OAGMASK {SIZE} {SIZE}\n" + "\n".join(rows) + "\n"
    )
