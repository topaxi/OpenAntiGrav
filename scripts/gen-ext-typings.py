#!/usr/bin/env python3
"""TypeScript typings for the WebAssembly extension ABI, generated from the layout.

`crates/ext-abi/src/lib.rs` is the one definition of the I/O buffer (`oag_ext_abi`): the
host and the Rust guest SDK both compile against it. This reads its constants (offsets,
lengths, codes, flags) and writes `assets/mods/examples/types/oag-abi.d.ts`, so a
JavaScript or TypeScript mod's view of the buffer cannot drift from it.

    scripts/gen-ext-typings.py            write the typings
    scripts/gen-ext-typings.py --check    fail if the committed file or a JavaScript example's
                                          own copy of an ABI constant differs (the gate:
                                          `just check-extensions`)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ABI = ROOT / "crates/ext-abi/src/lib.rs"
EXAMPLES = ROOT / "assets/mods/examples"
OUTPUT = EXAMPLES / "types/oag-abi.d.ts"
JS_SOURCES = ["wall-penalty-js/src/main.js"]


def read_constants():
    """Every `const NAME: ty = expr;` of the ABI crate: name -> (type, value)."""
    found = re.findall(
        r"^(?:pub )?const ([A-Z][A-Z0-9_]*): (u8|u16|u32|usize|f32) = (.+);$",
        ABI.read_text(encoding="utf-8"),
        re.M,
    )
    values = {}
    kinds = {}
    for name, kind, expr in found:
        expr = expr.replace("u8::MAX", "255")
        expr = re.sub(r"\b(\d+)\.(\d+)\b", r"\1.\2", expr)
        try:
            values[name] = eval(expr, {"__builtins__": {}}, dict(values))
        except NameError:
            sys.exit(f"{ABI}: cannot evaluate {name} = {expr}")
        kinds[name] = kind
    return values, kinds


def camel(name):
    return "".join(part.capitalize() for part in name.lower().split("_"))


def lower_camel(name):
    text = camel(name)
    return text[0].lower() + text[1:]


def number(value):
    return str(int(value)) if float(value).is_integer() else repr(value)


def generate(values, kinds):
    def group(prefix, kind="u8"):
        return [
            (name[len(prefix) :], values[name])
            for name in values
            if name.startswith(prefix) and kinds[name] == kind
        ]

    events = group("EVENT_")
    commands = group("COMMAND_")
    flags = group("CRAFT_")
    layout = [
        name
        for name in values
        if kinds[name] in ("usize", "u32", "f32") and not name.startswith("MAX_PAD")
    ]
    out = [
        "// Generated by scripts/gen-ext-typings.py from crates/ext-abi/src/lib.rs.",
        "// Do not edit: `just check-extensions` fails when this differs from the layout.",
        "//",
        "// The I/O buffer of a WebAssembly extension (ABI 1): the host writes the observation",
        "// at `oag_io()` before `tick`, and reads the state and the reply from it after. All",
        "// fields are little-endian. Each constant is typed as its value, so a script that",
        "// restates one with another number is a type error.",
        "",
    ]
    for name in layout:
        out.append(f"export declare const {name}: {number(values[name])};")
    out += [
        "",
        "/** The code of an event record's `kind` byte. */",
        "export declare const EventKind: {",
    ]
    out += [f"  readonly {camel(n)}: {v};" for n, v in events if n not in ("KIND", "SLOT", "INDEX")]
    out += ["};", "", "/** The code of a command record's `kind` byte. */", "export declare const CommandKind: {"]
    out += [f"  readonly {camel(n)}: {v};" for n, v in commands]
    out += [
        "};",
        "",
        "/** Bits of a craft record's `flags` byte. */",
        "export declare const CraftFlag: {",
    ]
    out += [f"  readonly {camel(n)}: {v};" for n, v in flags if n in ("PERSON", "FIRE_HELD", "RACING", "SHIELDED")]
    out += [
        "};",
        "",
        "/** Set in a `fire-effect` command's argument for the sending mod's own effect. */",
        f"export declare const OWN_FLAG: {values['OWN_FLAG']};",
        "",
        "/** One event, at `EVENTS_AT + i * EVENT_LEN`. */",
        "export interface EventRecord {",
        f"  /** byte {values['EVENT_KIND']}: an `EventKind`. */",
        "  kind: number;",
        f"  /** byte {values['EVENT_SLOT']}. */",
        "  slot: number;",
        f"  /** u16 at byte {values['EVENT_INDEX']}: the pad or trigger index, the weapon of a hit. */",
        "  index: number;",
        f"  /** f32 at byte {values['EVENT_VALUE']}: a hit's amount. */",
        "  value: number;",
        "}",
        "",
        "/** One craft, at `CRAFTS_AT + slot * CRAFT_LEN`. */",
        "export interface CraftRecord {",
        f"  /** byte {values['CRAFT_PICKUP']}: the held pickup. */",
        "  pickup: number;",
        f"  /** byte {values['CRAFT_FLAGS']}: `CraftFlag` bits. */",
        "  flags: number;",
        f"  /** byte {values['CRAFT_LAP']}: the lap being driven, 1-based. */",
        "  lap: number;",
        f"  /** byte {values['CRAFT_LAPS_TARGET']}: the laps the race ends after, 0 for none. */",
        "  lapsTarget: number;",
        f"  /** f32 at byte {values['CRAFT_SHIELD']}. */",
        "  shield: number;",
        f"  /** f32 at byte {values['CRAFT_SHIELD_MAX']}. */",
        "  shieldMax: number;",
        f"  /** f32 at byte {values['CRAFT_SPEED']}: km/h. */",
        "  speed: number;",
        "}",
        "",
        "/** The observation, as the host lays it out from the start of the buffer. */",
        "export interface Observation {",
        f"  /** u32 at byte {values['ABI_AT']}: the ABI major. */",
        "  abi: number;",
        f"  /** u64 at byte {values['TICK_AT']}: the world tick. */",
        "  tick: bigint;",
        f"  /** u32 at byte {values['SLOTS_AT']}. */",
        "  slots: number;",
        f"  /** u32 at byte {values['ACTIVE_AT']}: one bit per slot holding a craft. */",
        "  active: number;",
        f"  /** u32 at byte {values['EVENT_COUNT_AT']}. */",
        "  eventCount: number;",
        f"  /** u32 at byte {values['STATE_LEN_AT']}: the state blob's length. */",
        "  stateLength: number;",
        f"  /** From byte {values['EVENTS_AT']}, `EVENT_LEN` each, at most `MAX_EVENTS`. */",
        "  events: EventRecord[];",
        f"  /** From byte {values['STATE_AT']}: the module's state blob, in and out. */",
        "  state: Uint8Array;",
        "  /** One per grid slot, from `CRAFTS_AT`. */",
        "  crafts: CraftRecord[];",
        "}",
        "",
        "/** One command, at `REPLY_AT + 4 + i * COMMAND_LEN`. */",
        "export interface CommandRecord {",
        f"  /** byte {values['COMMAND_KIND']}: a `CommandKind`. */",
        "  kind: number;",
        f"  /** byte {values['COMMAND_SLOT']}. */",
        "  slot: number;",
        f"  /** u16 at byte {values['COMMAND_ARG']}. */",
        "  arg: number;",
        f"  /** f32 at byte {values['COMMAND_VALUE']}. */",
        "  value: number;",
        f"  /** u32 at byte {values['COMMAND_WORD']}. */",
        "  word: number;",
        "}",
        "",
        "/** The reply: `u32` count at `REPLY_AT`, then the commands, at most `MAX_COMMANDS`. */",
        "export interface Reply {",
        "  count: number;",
        "  commands: CommandRecord[];",
        "}",
        "",
    ]
    return "\n".join(out)


def check_scripts(values, kinds):
    """A JavaScript example restates ABI numbers as `const NAME = n;`; each must match."""
    codes = {}
    for name, value in values.items():
        if kinds[name] == "u8" or name in ("OWN_FLAG",):
            codes[name] = value
    problems = []
    for relative in JS_SOURCES:
        text = (EXAMPLES / relative).read_text(encoding="utf-8")
        for name, literal in re.findall(r"^const ([A-Z][A-Z0-9_]*) = (0x[0-9a-fA-F]+|\d+);", text, re.M):
            if name in values and int(literal, 0) != int(values[name]):
                problems.append(f"{relative}: {name} = {literal}, the ABI says {number(values[name])}")
    return problems


def main():
    values, kinds = read_constants()
    text = generate(values, kinds)
    if "--check" not in sys.argv:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return
    if not EXAMPLES.joinpath("wall-penalty-js").exists():
        print("mod examples not checked out: typings check skipped")
        return
    problems = check_scripts(values, kinds)
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
        problems.append(f"{OUTPUT.relative_to(ROOT)} is stale: run scripts/gen-ext-typings.py")
    if problems:
        sys.exit("\n".join(problems))
    print("extension typings match crates/ext-abi")


main()
